<?php

declare(strict_types=1);

namespace PhpPgAdmin\Modules\Schemas\Http\Controllers;

use League\Route\Http\Exception\BadRequestException;
use League\Route\Http\Exception\NotFoundException;
use PhpPgAdmin\Core\Database\ConnectionPool;
use Psr\Http\Message\ServerRequestInterface;

/**
 * phpMyAdmin's data dictionary (database/data_dictionary): every table of the database, or of
 * one schema, with its comment, its columns (type, NULL, default, the column a foreign key
 * links it to, comment) and its indexes (name, method, uniqueness, columns with their
 * collation and NULL ordering, comment). Tables, partitioned tables and their partitions,
 * views, materialized views and foreign tables are listed, schema by schema.
 */
final class DataDictionaryController
{
    private const string RELATIONS = <<<'SQL'
        SELECT c.oid, n.nspname AS schema, c.relname AS name, c.relkind::text AS kind,
               pg_catalog.obj_description(c.oid, 'pg_class') AS comment
        FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f')
          AND n.nspname !~ '^pg_' AND n.nspname <> 'information_schema'
          AND ($1::text IS NULL OR n.nspname = $1)
        ORDER BY n.nspname, c.relname
        SQL;

    private const string COLUMNS = <<<'SQL'
        SELECT a.attrelid AS relid, a.attname AS name,
               pg_catalog.format_type(a.atttypid, a.atttypmod) AS type,
               NOT a.attnotnull AS nullable,
               CASE
                   WHEN a.attidentity = 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
                   WHEN a.attidentity = 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
                   WHEN a.attgenerated = 's' THEN 'GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                   WHEN a.attgenerated = 'v' THEN 'GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') VIRTUAL'
                   ELSE pg_catalog.pg_get_expr(d.adbin, d.adrelid)
               END AS "default",
               EXISTS (SELECT 1 FROM pg_catalog.pg_constraint p WHERE p.conrelid = a.attrelid AND p.contype = 'p' AND a.attnum = ANY (p.conkey)) AS primary_key,
               (SELECT json_agg(json_build_object('schema', fn.nspname, 'table', fc.relname, 'column', fa.attname) ORDER BY f.conname)
                FROM pg_catalog.pg_constraint f
                JOIN pg_catalog.pg_class fc ON fc.oid = f.confrelid
                JOIN pg_catalog.pg_namespace fn ON fn.oid = fc.relnamespace
                JOIN pg_catalog.pg_attribute fa ON fa.attrelid = f.confrelid AND fa.attnum = f.confkey[pg_catalog.array_position(f.conkey, a.attnum)]
                WHERE f.conrelid = a.attrelid AND f.contype = 'f' AND a.attnum = ANY (f.conkey)) AS links,
               pg_catalog.col_description(a.attrelid, a.attnum) AS comment
        FROM pg_catalog.pg_attribute a
        LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid IN (SELECT pg_catalog.unnest($1::oid[]))
          AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attrelid, a.attnum
        SQL;

    private const string INDEXES = <<<'SQL'
        SELECT i.indrelid AS relid, ic.relname AS name, am.amname AS method, i.indisunique AS "unique", i.indisprimary AS "primary",
               pg_catalog.obj_description(i.indexrelid, 'pg_class') AS comment,
               (SELECT json_agg(json_build_object(
                           'name', pg_catalog.pg_get_indexdef(i.indexrelid, k.n::int, true),
                           'collation', CASE WHEN co.oid IS NULL OR co.collname = 'default' THEN NULL ELSE co.collname END,
                           'nulls', CASE WHEN k.n > i.indnkeyatts THEN NULL
                                         WHEN pg_catalog.pg_index_column_has_property(i.indexrelid, k.n::int, 'nulls_first') THEN 'NULLS FIRST'
                                         ELSE 'NULLS LAST' END,
                           'included', k.n > i.indnkeyatts) ORDER BY k.n)
                FROM pg_catalog.generate_series(1, i.indnatts) AS k(n)
                LEFT JOIN pg_catalog.pg_collation co ON co.oid = i.indcollation[k.n - 1]) AS columns
        FROM pg_catalog.pg_index i
        JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
        JOIN pg_catalog.pg_am am ON am.oid = ic.relam
        WHERE i.indrelid IN (SELECT pg_catalog.unnest($1::oid[]))
        ORDER BY i.indrelid, i.indisprimary DESC, ic.relname
        SQL;

    /** @return array<string, mixed> */
    public function show(ServerRequestInterface $request, array $args): array
    {
        $database = rawurldecode((string) ($args['db'] ?? ''));
        if ($database === '') {
            throw new BadRequestException('A database name is required.');
        }
        $schema = $request->getQueryParams()['schema'] ?? null;
        $schema = is_string($schema) && $schema !== '' ? $schema : null;
        $conn = ConnectionPool::from($request)->for($database);
        if ($schema !== null && $conn->scalar('SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = $1', [$schema]) === null) {
            throw new NotFoundException(sprintf('There is no schema "%s".', $schema));
        }

        $relations = $conn->rows(self::RELATIONS, [$schema]);
        $oids = '{' . implode(',', array_map(static fn (array $r): string => (string) (int) $r['oid'], $relations)) . '}';
        $columns = [];
        foreach ($conn->rows(self::COLUMNS, [$oids]) as $row) {
            $row['links'] = $row['links'] === null ? [] : json_decode((string) $row['links'], true);
            $columns[(int) $row['relid']][] = $row;
        }
        $indexes = [];
        foreach ($conn->rows(self::INDEXES, [$oids]) as $row) {
            $row['columns'] = json_decode((string) $row['columns'], true) ?? [];
            $indexes[(int) $row['relid']][] = $row;
        }

        $tables = [];
        foreach ($relations as $relation) {
            $oid = (int) $relation['oid'];
            $tables[] = [
                'schema' => $relation['schema'],
                'name' => $relation['name'],
                'kind' => $relation['kind'],
                'comment' => $relation['comment'],
                'columns' => array_map(static function (array $column): array {
                    unset($column['relid']);

                    return $column;
                }, $columns[$oid] ?? []),
                'indexes' => array_map(static function (array $index): array {
                    unset($index['relid']);

                    return $index;
                }, $indexes[$oid] ?? []),
            ];
        }

        return [
            'database' => $database,
            'schema' => $schema,
            'comment' => $conn->scalar('SELECT pg_catalog.shobj_description(oid, \'pg_database\') FROM pg_catalog.pg_database WHERE datname = current_database()'),
            'tables' => $tables,
        ];
    }
}
