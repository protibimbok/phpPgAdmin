-- Demo database for the documentation screenshots and walkthroughs.
--
--   psql -U postgres -c 'DROP DATABASE IF EXISTS bookshop' -c 'CREATE DATABASE bookshop'
--   psql -U postgres -d bookshop -f docs/demo/seed.sql
--
-- It holds one object of (nearly) every kind phpPgAdmin manages, with enough rows to page through.
-- docs/scripts/reset-demo.sh rebuilds it from scratch.

SET client_min_messages = warning;

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS pgstattuple;
CREATE EXTENSION IF NOT EXISTS citext;

DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'bookshop_staff') THEN
    CREATE ROLE bookshop_staff NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'bookshop_clerk') THEN
    CREATE ROLE bookshop_clerk LOGIN PASSWORD 'clerk' IN ROLE bookshop_staff;
  END IF;
END $$;

CREATE SCHEMA inventory;
COMMENT ON SCHEMA inventory IS 'Stock, warehouses and suppliers';

-- Types --------------------------------------------------------------------------------------

CREATE TYPE public.order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled');
CREATE TYPE public.address AS (street text, city text, postcode text, country char(2));
CREATE TYPE public.price_range AS RANGE (subtype = numeric);
CREATE DOMAIN public.isbn13 AS char(13) CHECK (VALUE ~ '^[0-9]{13}$');
CREATE DOMAIN public.email AS citext CONSTRAINT email_has_at CHECK (VALUE LIKE '%@%');
CREATE COLLATION public.case_insensitive (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

CREATE TEXT SEARCH CONFIGURATION public.book_search (COPY = pg_catalog.english);

-- Tables -------------------------------------------------------------------------------------

CREATE TABLE public.authors (
  id         serial PRIMARY KEY,
  name       text NOT NULL,
  born       date,
  country    char(2),
  bio        text,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.authors IS 'People who wrote the books we sell';
COMMENT ON COLUMN public.authors.country IS 'ISO 3166-1 alpha-2';

CREATE TABLE public.publishers (
  id      integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name    text NOT NULL UNIQUE,
  website text,
  address public.address
);

CREATE TABLE public.books (
  id           serial PRIMARY KEY,
  isbn         public.isbn13 UNIQUE,
  title        text NOT NULL,
  author_id    integer NOT NULL REFERENCES public.authors (id) ON DELETE RESTRICT,
  publisher_id integer REFERENCES public.publishers (id) ON DELETE SET NULL,
  published    date,
  pages        integer CHECK (pages > 0),
  price        numeric(8, 2) NOT NULL DEFAULT 0 CONSTRAINT price_not_negative CHECK (price >= 0),
  tags         text[] NOT NULL DEFAULT '{}',
  details      jsonb,
  cover        bytea,
  search       tsvector GENERATED ALWAYS AS (to_tsvector('public.book_search', title)) STORED
);
CREATE INDEX books_author_idx ON public.books (author_id);
CREATE INDEX books_search_idx ON public.books USING gin (search);
CREATE INDEX books_title_trgm_idx ON public.books USING gin (title gin_trgm_ops);
CREATE STATISTICS public.books_author_publisher (dependencies, ndistinct) ON author_id, publisher_id FROM public.books;

CREATE TABLE public.customers (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      public.email NOT NULL UNIQUE,
  full_name  text NOT NULL COLLATE public.case_insensitive,
  address    public.address,
  vip        boolean NOT NULL DEFAULT false,
  joined     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.orders (
  id          bigserial,
  customer_id bigint NOT NULL REFERENCES public.customers (id),
  status      public.order_status NOT NULL DEFAULT 'pending',
  placed_at   timestamptz NOT NULL DEFAULT now(),
  total       numeric(10, 2) NOT NULL DEFAULT 0,
  PRIMARY KEY (id, placed_at)
) PARTITION BY RANGE (placed_at);
CREATE TABLE public.orders_2025 PARTITION OF public.orders FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE public.orders_2026 PARTITION OF public.orders FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

CREATE TABLE public.order_items (
  order_id  bigint NOT NULL,
  placed_at timestamptz NOT NULL,
  book_id   integer NOT NULL REFERENCES public.books (id),
  quantity  integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  price     numeric(8, 2) NOT NULL,
  PRIMARY KEY (order_id, book_id),
  FOREIGN KEY (order_id, placed_at) REFERENCES public.orders (id, placed_at) ON DELETE CASCADE
);

CREATE TABLE public.reviews (
  id          serial PRIMARY KEY,
  book_id     integer NOT NULL REFERENCES public.books (id) ON DELETE CASCADE,
  customer_id bigint NOT NULL REFERENCES public.customers (id) ON DELETE CASCADE,
  rating      smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body        text,
  hidden      boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;
CREATE POLICY reviews_visible ON public.reviews FOR SELECT TO bookshop_staff USING (NOT hidden);

CREATE TABLE public.audit_log (
  id         bigserial PRIMARY KEY,
  table_name text NOT NULL,
  action     text NOT NULL,
  row_data   jsonb,
  changed_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.ebooks (
  format   text NOT NULL DEFAULT 'epub',
  file_size_kb integer
) INHERITS (public.books);

CREATE TABLE inventory.warehouses (
  id    serial PRIMARY KEY,
  code  text NOT NULL UNIQUE,
  city  text NOT NULL
);

CREATE TABLE inventory.stock (
  warehouse_id integer NOT NULL REFERENCES inventory.warehouses (id),
  book_id      integer NOT NULL REFERENCES public.books (id),
  quantity     integer NOT NULL DEFAULT 0,
  PRIMARY KEY (warehouse_id, book_id)
);

CREATE TABLE inventory.promotions (
  id       serial PRIMARY KEY,
  book_id  integer NOT NULL REFERENCES public.books (id),
  discount numeric(4, 2) NOT NULL,
  during   tstzrange NOT NULL,
  EXCLUDE USING gist (book_id WITH =, during WITH &&)
);

CREATE SEQUENCE public.invoice_number START 1000 INCREMENT 1 CACHE 1;

-- Routines -----------------------------------------------------------------------------------

CREATE FUNCTION public.book_count(author integer) RETURNS bigint
  LANGUAGE sql STABLE AS $$ SELECT count(*) FROM public.books WHERE author_id = author $$;
COMMENT ON FUNCTION public.book_count(integer) IS 'Number of books by one author';

CREATE FUNCTION public.apply_discount(price numeric, percent numeric DEFAULT 10) RETURNS numeric
  LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  result numeric;
BEGIN
  IF percent < 0 OR percent > 100 THEN
    RAISE EXCEPTION 'percent must be between 0 and 100, got %', percent;
  END IF;
  result := round(price * (100 - percent) / 100, 2);
  RETURN result;
END
$$;

CREATE PROCEDURE public.restock(book integer, warehouse integer, amount integer)
  LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO inventory.stock (warehouse_id, book_id, quantity) VALUES (warehouse, book, amount)
  ON CONFLICT (warehouse_id, book_id) DO UPDATE SET quantity = inventory.stock.quantity + EXCLUDED.quantity;
END
$$;

CREATE FUNCTION public.log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO public.audit_log (table_name, action, row_data)
  VALUES (TG_TABLE_NAME, TG_OP, to_jsonb(COALESCE(NEW, OLD)));
  RETURN COALESCE(NEW, OLD);
END
$$;
CREATE TRIGGER books_audit AFTER INSERT OR UPDATE OR DELETE ON public.books
  FOR EACH ROW EXECUTE FUNCTION public.log_change();

CREATE FUNCTION public.price_sum_state(numeric, numeric) RETURNS numeric
  LANGUAGE sql IMMUTABLE AS $$ SELECT coalesce($1, 0) + coalesce($2, 0) $$;
CREATE AGGREGATE public.total_price(numeric) (SFUNC = public.price_sum_state, STYPE = numeric, INITCOND = '0');

CREATE FUNCTION public.isbn_eq(public.isbn13, public.isbn13) RETURNS boolean
  LANGUAGE sql IMMUTABLE AS $$ SELECT $1::text = $2::text $$;
CREATE OPERATOR public.=== (LEFTARG = public.isbn13, RIGHTARG = public.isbn13, FUNCTION = public.isbn_eq);

CREATE RULE audit_log_no_delete AS ON DELETE TO public.audit_log DO INSTEAD NOTHING;

-- Views --------------------------------------------------------------------------------------

CREATE VIEW public.book_catalogue AS
  SELECT b.id, b.title, a.name AS author, p.name AS publisher, b.price, b.published
  FROM public.books b
  JOIN public.authors a ON a.id = b.author_id
  LEFT JOIN public.publishers p ON p.id = b.publisher_id;
COMMENT ON VIEW public.book_catalogue IS 'Books with author and publisher names';

CREATE MATERIALIZED VIEW public.author_stats AS
  SELECT a.id, a.name, count(b.id) AS books, coalesce(avg(r.rating), 0)::numeric(3, 2) AS avg_rating
  FROM public.authors a
  LEFT JOIN public.books b ON b.author_id = a.id
  LEFT JOIN public.reviews r ON r.book_id = b.id
  GROUP BY a.id, a.name;

